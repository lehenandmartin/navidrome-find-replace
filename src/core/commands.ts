import type { Track } from './types'

export interface FixPair {
  old: Track
  new: Track
}

/** Quote for POSIX shells unless the value is obviously safe. */
export function shellQuote(s: string): string {
  return /^[A-Za-z0-9_.:/-]+$/.test(s) ? s : `'${s.replace(/'/g, `'\\''`)}'`
}

export interface FixCommandsResult {
  script: string
  commandCount: number
  /** Pairs left out, with the reason. */
  skipped: { pair: FixPair; reason: string }[]
}

/**
 * Build `navidrome missing fix <missing id> <target id>` commands.
 *
 * Only pairs whose old track is flagged missing qualify: the command refuses anything else.
 * `prefix` lets the user prepend e.g. `docker exec navidrome`.
 */
export function buildFixCommands(pairs: FixPair[], opts: { prefix?: string; now?: Date } = {}): FixCommandsResult {
  const prefix = opts.prefix?.trim() ? opts.prefix.trim() + ' ' : ''
  const skipped: FixCommandsResult['skipped'] = []
  const lines: string[] = []
  const seenOld = new Set<string>()
  const seenNew = new Set<string>()
  for (const p of pairs) {
    if (!p.old.missing) {
      skipped.push({ pair: p, reason: 'Old track is not flagged as missing (delete its file and rescan first)' })
    } else if (p.new.missing) {
      skipped.push({ pair: p, reason: 'New track is itself missing' })
    } else if (seenOld.has(p.old.id)) {
      skipped.push({ pair: p, reason: 'Old track already used in another command' })
    } else if (seenNew.has(p.new.id)) {
      // The target id is deleted by the first fix, so a second one would fail.
      skipped.push({ pair: p, reason: 'New track already used as a target in another command' })
    } else {
      seenOld.add(p.old.id)
      seenNew.add(p.new.id)
      lines.push(`# ${oneLine(p.old.artist)} - ${oneLine(p.old.title)}  →  ${oneLine(p.new.album)}`)
      lines.push(`${prefix}navidrome missing fix ${shellQuote(p.old.id)} ${shellQuote(p.new.id)}`)
    }
  }
  const header = [
    '#!/bin/sh',
    '# Generated by navidrome-playlist-replace on ' + (opts.now ?? new Date()).toISOString(),
    '#',
    '# WARNING: these commands are IRREVERSIBLE. Make a backup first:',
    `#   ${prefix}navidrome backup create`,
    '#',
    '# Each command moves ratings, play counts and playlist entries of ALL users from the new',
    '# track onto the missing one, then deletes the new track id (the missing id is kept).',
    '# Run them before purging missing files.',
    'set -e',
    '',
  ]
  return { script: [...header, ...lines, ''].join('\n'), commandCount: lines.length / 2, skipped }
}

function oneLine(s: string): string {
  return (s ?? '').replace(/[\r\n]+/g, ' ')
}
